"""Export native-painted layers so the jig works offline with live controls."""

import base64
import hashlib
import itertools
import json
from pathlib import Path
import sys
from functools import lru_cache

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "preview"))
from fixtures import CASES, fixture
from render import render, render_layer
from landscapes import STYLES
from export_examples import export as export_examples


@lru_cache(maxsize=None)
def trail_image(own, team, partner, person, success, gap, width, solid, frame, landscape):
    values = dict(own=own, team=team, partner=partner, person=person, goal=500,
                  status="Synced" if success else "Hold badges back to back")
    if success:
        values["success_age"] = 400
    tuning = dict(walkerGap=gap, pathWidth=width, solidPartner=bool(solid), landscape=landscape)
    return render_layer(values, tuning, "trail", frame)


class Bundle:
    def __init__(self):
        self.images = {}
        self.lookup = {}

    def add(self, key, image):
        digest = hashlib.sha256(image).hexdigest()[:16]
        self.images.setdefault(digest, "data:image/png;base64," + base64.b64encode(image).decode())
        self.lookup[key] = digest

    def write(self, name):
        target = ROOT / "generated" / (name + ".js")
        target.parent.mkdir(exist_ok=True)
        data = dict(images=self.images, lookup=self.lookup)
        target.write_text("// Generated by export.py from the native Python painter.\nwindow.nativeLayers=window.nativeLayers||{};\nwindow.nativeLayers.%s=%s;\n" % (name, json.dumps(data, separators=(",", ":"))))
        print(name, len(self.images), "unique native layers", flush=True)


def main():
    output = ROOT / "renders"
    output.mkdir(exist_ok=True)
    header, scenery, trail = Bundle(), Bundle(), Bundle()
    for name, _, _, _ in CASES:
        for person in (0, 1):
            values = fixture(name, 500, person)
            (output / ("reference-%s-%s.png" % (name, person))).write_bytes(render(values, baseline=True, fatal=name == "fatal"))
        if name == "fatal":
            (output / "fatal.png").write_bytes(render(values, fatal=True))
            continue
        ages = range(0, 101, 5) if name == "holding" else (
            range(0, 601, 100) if name in ("success", "no_change", "zero_sync") else (400,))
        for size, age in itertools.product((3, 4, 5), ages):
            values = fixture(name, 500, 0)
            if name in ("success", "no_change", "zero_sync"):
                values["success_age"] = age
            elif name == "holding":
                values["progress"] = age / 100
            image = render_layer(values, dict(countSize=size), "header")
            header.add("%s|%s|%s" % (name, size, age), image)
        for person, gap, width, solid, frame, landscape in itertools.product((0, 1), (12, 16, 20), (3, 4, 5), (0, 1), (0, 1), [s[0] for s in STYLES]):
            values = fixture(name, 500, person)
            image = trail_image(values["own"], values["team"], values["partner"], person,
                                "success_age" in values, gap, width, solid, frame, landscape)
            trail.add("%s|%s|%s|%s|%s|%s|%s" % (name, person, gap, width, solid, frame, landscape), image)
    for landscape, sky, height, reached in itertools.product([s[0] for s in STYLES], ("gradient", "solid"), (18, 22, 26), (0, 1)):
        image = render_layer(fixture("goal" if reached else "pending", 500, 0), dict(landscape=landscape, sky=sky, lighthouseHeight=height), "scenery")
        scenery.add("%s|%s|%s|%s" % (landscape, sky, height, reached), image)
    header.write("header")
    scenery.write("scenery")
    trail.write("trail")
    cases = [dict(id=i, group=g, title=t, note=n, reached=i in ("goal", "beyond", "large"), success=i in ("success", "no_change", "zero_sync")) for i, g, t, n in CASES]
    (ROOT / "generated" / "cases.js").write_text("window.walkingCases=" + json.dumps(cases) + ";\n")
    export_examples(ROOT)


if __name__ == "__main__":
    main()
