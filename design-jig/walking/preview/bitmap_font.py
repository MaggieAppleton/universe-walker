def width(text, scale=1):
    return max(0, sum(len(GLYPHS.get(ch, GLYPHS["?"])[0]) + 1 for ch in text.upper()) - 1) * scale


def text(painter, value, x, y, scale, pen):
    cursor = int(x)
    for ch in value.upper():
        rows = GLYPHS.get(ch, GLYPHS["?"])
        for row, pixels in enumerate(rows):
            at = 0
            while at < len(pixels):
                if pixels[at] != "#":
                    at += 1
                    continue
                end = at + 1
                while end < len(pixels) and pixels[end] == "#":
                    end += 1
                painter.rect(cursor + at * scale, y + row * scale, (end - at) * scale, scale, pen)
                at = end
        cursor += (len(rows[0]) + 1) * scale
